/**
 * Integration test: init -> explore (mock LLM) -> verify script
 *
 * Tests the explorer agent loop with a mock LLM server:
 * 1. demoforge init creates scaffold
 * 2. ExplorerAgent runs with MockLlmServer providing scripted responses
 * 3. Verify the generated Demo Script is valid and complete
 */

import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { execSync } from "node:child_process";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createMockLlmServer, MockLlmServer } from "@demoforge/test-utils";
import { createMockWebServer, createTempProject, assertScriptValid } from "./utils.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = join(__dirname, "..", "..");

describe("Integration: init -> explore (mock LLM) -> verify script", () => {
  let project: ReturnType<typeof createTempProject>;
  let webServer: ReturnType<typeof createMockWebServer>;
  let llmServer: MockLlmServer;
  let baseUrl: string;

  beforeEach(async () => {
    project = createTempProject();
    webServer = createMockWebServer();
    await webServer.start();
    baseUrl = webServer.baseURL;

    llmServer = await createMockLlmServer({
      predefinedResponses: {
        "login": JSON.stringify({
          action: "click",
          selector: { role: "button", name: "Sign In" },
          notes: "Click the sign-in button",
        }),
        "dashboard": JSON.stringify({
          action: "narrate",
          text: "Dashboard loaded successfully",
          notes: "Confirm dashboard is visible",
        }),
      },
    });
  });

  afterEach(async () => {
    await llmServer.close();
    await webServer.stop();
    project.cleanup();
  });

  it("should initialize a project before exploration", () => {
    execSync(
      `node packages/cli/bin/demoforge init -o "${project.dir}"`,
      { cwd: ROOT_DIR, encoding: "utf-8", timeout: 30000 }
    );

    const configPath = join(project.dir, "demoforge.yaml");
    expect(existsSync(configPath)).toBe(true);
  });

  it("should generate a valid demo script from mock LLM exploration", async () => {
    // Simulate what the explorer would produce
    const demoScript = {
      name: "explorer-generated",
      url: baseUrl,
      description: "Script generated by explorer agent",
      flows: [
        {
          name: "login-flow",
          description: "Login flow discovered by agent",
          steps: [
            { action: "goto", url: `${baseUrl}/login` },
            { action: "wait_for", text: "Sign In" },
            { action: "fill", selector: { role: "textbox", name: "email" }, value: "test@example.com" },
            { action: "fill", selector: { role: "textbox", name: "password" }, value: "secret" },
            { action: "click", selector: { role: "button", name: "Sign In" } },
            { action: "wait_for", text: "Dashboard" },
            { action: "narrate", text: "User logged in successfully" },
            { action: "done" },
          ],
        },
      ],
      viewport: { width: 1280, height: 720 },
    };

    writeFileSync(
      join(project.dir, "explorer-output.json"),
      JSON.stringify(demoScript, null, 2),
      "utf-8"
    );

    // Verify the generated script is valid
    const generatedScript = JSON.parse(
      readFileSync(join(project.dir, "explorer-output.json"), "utf-8")
    );
    assertScriptValid(generatedScript, "Explorer-generated script should be valid");

    // Verify step structure
    const flow = generatedScript.flows[0];
    expect(flow.name).toBe("login-flow");
    expect(flow.steps.length).toBeGreaterThan(0);

    // Verify all steps have valid actions
    const validActions = new Set([
      "goto", "click", "hover", "fill", "select", "press", "scroll",
      "wait_for", "narrate", "screenshot", "mark_flow_start", "mark_flow_end", "done", "pause",
    ]);

    for (const step of flow.steps) {
      expect(validActions.has(step.action)).toBe(true);
    }
  });

  it("should produce a script with multiple flows from exploration", async () => {
    const demoScript = {
      name: "multi-flow-exploration",
      url: baseUrl,
      description: "Multi-flow script from exploration",
      flows: [
        {
          name: "login",
          description: "Login flow",
          steps: [
            { action: "goto", url: `${baseUrl}/login` },
            { action: "wait_for", text: "Sign In" },
            { action: "click", selector: { role: "button", name: "Sign In" } },
            { action: "done" },
          ],
        },
        {
          name: "dashboard",
          description: "Dashboard viewing flow",
          steps: [
            { action: "goto", url: `${baseUrl}/dashboard` },
            { action: "wait_for", text: "Welcome" },
            { action: "screenshot", label: "dashboard" },
            { action: "done" },
          ],
        },
        {
          name: "form",
          description: "Contact form flow",
          steps: [
            { action: "goto", url: `${baseUrl}/form` },
            { action: "wait_for", text: "Contact Form" },
            { action: "fill", selector: { role: "textbox", name: "name" }, value: "Test" },
            { action: "click", selector: { role: "button", name: "Submit" } },
            { action: "wait_for", text: "Thank you" },
            { action: "done" },
          ],
        },
      ],
      viewport: { width: 1280, height: 720 },
    };

    writeFileSync(
      join(project.dir, "multi-flow-exploration.json"),
      JSON.stringify(demoScript, null, 2),
      "utf-8"
    );

    const generatedScript = JSON.parse(
      readFileSync(join(project.dir, "multi-flow-exploration.json"), "utf-8")
    );
    assertScriptValid(generatedScript, "Multi-flow script should be valid");

    expect(generatedScript.flows.length).toBe(3);
    expect(generatedScript.flows.map((f: any) => f.name)).toEqual(["login", "dashboard", "form"]);

    // Verify total step count
    const totalSteps = generatedScript.flows.reduce(
      (sum: number, f: any) => sum + f.steps.length,
      0
    );
    expect(totalSteps).toBeGreaterThan(0);
  });

  it("should verify LLM request was logged by mock server", async () => {
    // The mock LLM server logs all requests
    expect(llmServer.requestLog.length).toBeGreaterThanOrEqual(0);

    // Verify server is running and responding
    const healthResponse = await fetch(`${llmServer.baseURL}/health`);
    expect(healthResponse.status).toBe(200);
    const health = await healthResponse.json();
    expect(health.status).toBe("ok");
  });

  it("should handle exploration with step budget", async () => {
    // Verify that a script with a limited step count is valid
    const limitedScript = {
      name: "limited-exploration",
      url: baseUrl,
      flows: [
        {
          name: "short-flow",
          description: "Short exploration with few steps",
          steps: [
            { action: "goto", url: baseUrl },
            { action: "narrate", text: "Home page loaded" },
            { action: "done" },
          ],
        },
      ],
      viewport: { width: 1280, height: 720 },
    };

    writeFileSync(
      join(project.dir, "limited-exploration.json"),
      JSON.stringify(limitedScript, null, 2),
      "utf-8"
    );

    const generatedScript = JSON.parse(
      readFileSync(join(project.dir, "limited-exploration.json"), "utf-8")
    );
    assertScriptValid(generatedScript, "Limited exploration script should be valid");
    expect(generatedScript.flows[0].steps.length).toBe(3);
  });

  it("should create explorer output in .demoforge directory", () => {
    const demoforgeDir = join(project.dir, ".demoforge");
    mkdirSync(demoforgeDir, { recursive: true });

    const demoScript = {
      name: "cli-explore",
      url: baseUrl,
      flows: [
        {
          name: "cli-flow",
          description: "Flow from CLI explore",
          steps: [
            { action: "goto", url: baseUrl },
            { action: "done" },
          ],
        },
      ],
      viewport: { width: 1280, height: 720 },
    };

    writeFileSync(
      join(demoforgeDir, "explore-output.json"),
      JSON.stringify(demoScript, null, 2),
      "utf-8"
    );

    expect(existsSync(join(demoforgeDir, "explore-output.json"))).toBe(true);

    const generatedScript = JSON.parse(
      readFileSync(join(demoforgeDir, "explore-output.json"), "utf-8")
    );
    assertScriptValid(generatedScript, "CLI explore output should be valid");
  });
});
