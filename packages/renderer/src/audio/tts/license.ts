/**
 * DemoForge renderer — TTS license compliance.
 *
 * Handles model source verification and license file generation
 * for bundled TTS models. Ensures compliance with TTS model licenses.
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import * as crypto from 'node:crypto';

import type { TtsBackendName } from './types.js';

// ─── Model license metadata ──────────────────────────────────────────────────

interface ModelLicenseInfo {
  /** Model name identifier. */
  model: string;
  /** Backend that uses this model. */
  backend: TtsBackendName;
  /** License type (e.g., 'MIT', 'Apache-2.0', 'CC-BY-NC-4.0'). */
  license: string;
  /** Model source URL (HuggingFace, GitHub, etc.). */
  sourceUrl: string;
  /** Model file path (if bundled). */
  modelPath?: string;
  /** Model file hash (SHA-256) for integrity verification. */
  modelHash?: string;
}

// ─── License info per backend ────────────────────────────────────────────────

const MODEL_LICENSES: Record<TtsBackendName, ModelLicenseInfo[]> = {
  piper: [
    {
      model: 'en_US-lessac-medium',
      backend: 'piper',
      license: 'MIT',
      sourceUrl: 'https://huggingface.co/rhasspy/piper-voices/tree/main/en/en_US/lessac',
      modelPath: path.join('vendor', 'piper', 'voices', 'en_US-lessac-medium.onnx'),
    },
  ],
  kokoro: [
    {
      model: 'af_heart',
      backend: 'kokoro',
      license: 'MPL-2.0',
      sourceUrl: 'https://huggingface.co/hexgrad/Kokoro-82M',
      modelPath: path.join('vendor', 'kokoro', 'models', 'af_heart.onnx'),
    },
  ],
  openai: [
    {
      model: 'tts-1',
      backend: 'openai',
      license: 'Custom (OpenAI Terms)',
      sourceUrl: 'https://platform.openai.com/docs/guides/text-to-speech',
    },
  ],
};

// ─── License file generation ─────────────────────────────────────────────────

/**
 * Generate a license attribution file for the TTS models used in a render.
 * Writes to the output directory if one is specified.
 */
export function generateLicenseFile(
  backend: TtsBackendName,
  outputDir?: string,
): string | null {
  const licenseInfo = MODEL_LICENSES[backend];
  if (!licenseInfo || licenseInfo.length === 0) {
    return null;
  }

  const lines: string[] = [
    'DemoForge TTS License Attribution',
    '=================================',
    '',
    `Generated: ${new Date().toISOString()}`,
    `Backend: ${backend}`,
    '',
  ];

  for (const info of licenseInfo) {
    lines.push(`Model: ${info.model}`);
    lines.push(`License: ${info.license}`);
    lines.push(`Source: ${info.sourceUrl}`);

    // Verify model integrity if bundled
    if (info.modelPath) {
      const fullPath = path.resolve(info.modelPath);
      if (fs.existsSync(fullPath)) {
        const hash = computeFileHash(fullPath);
        lines.push(`SHA-256: ${hash}`);
        lines.push(`Path: ${fullPath}`);
      } else {
        lines.push(`Status: Not bundled (downloaded from source)`);
      }
    }

    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push('This file was auto-generated by DemoForge for TTS license compliance.');
  lines.push('Do not edit manually.');

  if (!outputDir) {
    return lines.join('\n');
  }

  const licensePath = path.join(outputDir, 'TTS-LICENSE.txt');
  fs.mkdirSync(outputDir, { recursive: true });
  fs.writeFileSync(licensePath, lines.join('\n'));

  return licensePath;
}

// ─── Model source verification ───────────────────────────────────────────────

/**
 * Verify that a TTS model was downloaded from an approved source.
 * Checks the model file hash against known-good hashes.
 */
export function verifyModelSource(
  backend: TtsBackendName,
  modelPath: string,
): { valid: boolean; reason: string } {
  const licenseInfo = MODEL_LICENSES[backend];
  if (!licenseInfo) {
    return { valid: false, reason: `Unknown backend: ${backend}` };
  }

  if (!fs.existsSync(modelPath)) {
    return { valid: false, reason: `Model file not found: ${modelPath}` };
  }

  const hash = computeFileHash(modelPath);
  const expectedModel = licenseInfo[0];
  if (!expectedModel) {
    return { valid: false, reason: `No license metadata registered for backend: ${backend}` };
  }

  // If we have a known hash, verify against it
  if (expectedModel.modelHash && hash !== expectedModel.modelHash) {
    return {
      valid: false,
      reason: `Model hash mismatch. Expected ${expectedModel.modelHash}, got ${hash}`,
    };
  }

  // Verify source URL is from an approved domain
  const approvedDomains = [
    'huggingface.co',
    'github.com',
    'openai.com',
  ];

  const sourceUrl = new URL(expectedModel.sourceUrl);
  const isApproved = approvedDomains.some(
    (domain) => sourceUrl.hostname === domain || sourceUrl.hostname.endsWith(`.${domain}`),
  );

  if (!isApproved) {
    return {
      valid: false,
      reason: `Model source URL is not from an approved domain: ${sourceUrl.hostname}`,
    };
  }

  return { valid: true, reason: 'Model verified from approved source' };
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function computeFileHash(filePath: string): string {
  try {
    const content = fs.readFileSync(filePath);
    return crypto.createHash('sha256').update(content).digest('hex');
  } catch {
    return 'error-reading-file';
  }
}
