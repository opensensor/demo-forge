// ---------------------------------------------------------------------------
// loadConfig — resolve from CWD or parent directories
// ---------------------------------------------------------------------------

const CONFIG_FILENAMES = [
  "demoforge.yaml",
  "demoforge.yml",
];

/**
 * Recursively searches from `startDir` up to the filesystem root for a
 * demoforge.yaml / demoforge.yml file.
 */
function findConfigFile(startDir: string): string | null {
  let dir = path.resolve(startDir);
  const root = path.parse(dir).root;

  while (true) {
    for (const name of CONFIG_FILENAMES) {
      const candidate = path.join(dir, name);
      if (fs.existsSync(candidate)) {
        return candidate;
      }
    }
    if (dir === root) break;
    dir = path.dirname(dir);
  }

  return null;
}

/**
 * Parse and validate a YAML config object, merging with defaults.
 * Returns a fresh Config object.
 */
function parseConfig(raw: unknown, configPath: string): Config {
  const cfg = defaults();

  if (raw === null || raw === undefined || typeof raw !== "object") {
    throw new ConfigError(
      `Config file must be a YAML mapping, got ${raw === null ? "null" : typeof raw}`,
      { path: configPath },
    );
  }

  const obj = raw as Record<string, unknown>;

  // demo — required
  if (typeof obj.demo !== "string" || obj.demo.trim() === "") {
    throw new ConfigError(
      "Required field 'demo' must be a non-empty string",
      { path: configPath },
    );
  }
  cfg.demo = obj.demo.trim();

  // title — optional
  if (typeof obj.title === "string") {
    cfg.title = obj.title;
  }

  // llm — optional, merges with defaults
  if (obj.llm && typeof obj.llm === "object") {
    const llm = obj.llm as Record<string, unknown>;
    if (typeof llm.base_url === "string") cfg.llm.base_url = llm.base_url;
    if (typeof llm.model === "string") cfg.llm.model = llm.model;
    if (typeof llm.context_budget === "number" && llm.context_budget > 0) {
      cfg.llm.context_budget = llm.context_budget;
    }
  }

  // render — optional, merges with defaults
  if (obj.render && typeof obj.render === "object") {
    const render = obj.render as Record<string, unknown>;

    if (Array.isArray(render.viewports)) {
      cfg.render.viewports = (render.viewports as unknown[]).map((v) => {
        if (v && typeof v === "object") {
          const vc = v as Record<string, unknown>;
          return {
            width: typeof vc.width === "number" ? vc.width : 1440,
            height: typeof vc.height === "number" ? vc.height : 900,
          };
        }
        return { width: 1440, height: 900 };
      });
    }

    if (Array.isArray(render.themes)) {
      const validThemes = (render.themes as string[]).filter(
        (t): t is "light" | "dark" => t === "light" || t === "dark",
      );
      if (validThemes.length > 0) cfg.render.themes = validThemes;
    }

    if (Array.isArray(render.locales)) {
      const validLocales = (render.locales as string[]).filter(
        (l): l is string => typeof l === "string" && l.trim() !== "",
      );
      if (validLocales.length > 0) cfg.render.locales = validLocales;
    }
  }

  // seed — optional, merges with defaults
  if (obj.seed && typeof obj.seed === "object") {
    const seed = obj.seed as Record<string, unknown>;
    if (typeof seed.command === "string") cfg.seed.command = seed.command;
    if (typeof seed.timeout === "number" && seed.timeout > 0) {
      cfg.seed.timeout = seed.timeout;
    }
  }

  // redaction — optional array
  if (Array.isArray(obj.redaction)) {
    cfg.redaction = (obj.redaction as unknown[]).map((r) => {
      if (r && typeof r === "object") {
        const rule = r as Record<string, unknown>;
        const pattern = typeof rule.pattern === "string" ? rule.pattern : "";
        const label = typeof rule.label === "string" ? rule.label : "unknown";
        if (pattern) return { pattern, label };
      }
      return { pattern: "", label: "unknown" };
    }).filter((r) => r.pattern !== "");
  }

  // output — optional, merges with defaults
  if (obj.output && typeof obj.output === "object") {
    const output = obj.output as Record<string, unknown>;

    if (Array.isArray(output.formats)) {
      const validFormats = (output.formats as string[]).filter(
        (f): f is "mp4" | "webm" | "gif" | "webp" =>
          ["mp4", "webm", "gif", "webp"].includes(f),
      );
      if (validFormats.length > 0) cfg.output.formats = validFormats;
    }

    if (output.budgets && typeof output.budgets === "object") {
      const budgets = output.budgets as Record<string, unknown>;
      for (const key of ["mp4", "webm", "gif", "webp"] as const) {
        if (typeof budgets[key] === "number" && budgets[key]! > 0) {
          cfg.output.budgets[key] = budgets[key]!;
        }
      }
    }
  }

  // narration — optional, merges with defaults
  if (obj.narration && typeof obj.narration === "object") {
    const narr = obj.narration as Record<string, unknown>;
    if (typeof narr.mode === "string" && ["captions", "tts", "none"].includes(narr.mode)) {
      cfg.narration.mode = narr.mode as NarrationMode;
    }
    if (typeof narr.voice === "string") cfg.narration.voice = narr.voice;
    if (typeof narr.speed === "number" && narr.speed > 0) cfg.narration.speed = narr.speed;
  }

  // explorer — optional, merges with defaults
  if (obj.explorer && typeof obj.explorer === "object") {
    const expl = obj.explorer as Record<string, unknown>;
    if (typeof expl.maxSteps === "number" && expl.maxSteps > 0) {
      cfg.explorer.maxSteps = expl.maxSteps;
    }
    if (typeof expl.maxTime === "number" && expl.maxTime > 0) {
      cfg.explorer.maxTime = expl.maxTime;
    }
    if (expl.guardrails && typeof expl.guardrails === "object") {
      const gr = expl.guardrails as Record<string, unknown>;
      if (Array.isArray(gr.allowedOrigins)) {
        cfg.explorer.guardrails!.allowedOrigins = (gr.allowedOrigins as string[]).filter((o) => typeof o === "string" && o.trim() !== "");
      }
      if (Array.isArray(gr.destructiveButtonPatterns)) {
        cfg.explorer.guardrails!.destructiveButtonPatterns = (gr.destructiveButtonPatterns as string[]).filter((p) => typeof p === "string" && p.trim() !== "");
      }
      if (Array.isArray(gr.destructiveUrlPatterns)) {
        cfg.explorer.guardrails!.destructiveUrlPatterns = (gr.destructiveUrlPatterns as string[]).filter((p) => typeof p === "string" && p.trim() !== "");
      }
    }
  }

  return cfg;
}

/**
 * Load and validate a demoforge.yaml config.
 *
 * Searches from `cwd` (or current working directory) upward for a config
 * file. If found, parses and validates it. If not found, returns defaults
 * and logs a warning.
 *
 * @param cwd — directory to start searching from (defaults to process.cwd())
 * @returns a fresh Config object (never cached)
 */
export async function loadConfig(cwd?: string): Promise<Config> {
  const startDir = cwd ?? process.cwd();
  const configPath = findConfigFile(startDir);

  if (configPath === null) {
    console.warn(
      `[demoforge] No demoforge.yaml found (searched from ${startDir}). Using defaults.`,
    );
    return defaults();
  }

  let raw: unknown;
  try {
    const content = fs.readFileSync(configPath, "utf-8");
    raw = yaml.load(content);
  } catch (err) {
    if (err instanceof Error && "mark" in err) {
      // js-yaml MarkException — YAML parse error
      throw new ConfigError(
        `Failed to parse ${configPath}: ${err.message}`,
        { path: configPath },
      );
    }
    throw new ConfigError(
      `Failed to read ${configPath}: ${err instanceof Error ? err.message : String(err)}`,
      { path: configPath },
    );
  }

  return parseConfig(raw, configPath);
}

// ---------------------------------------------------------------------------
// initConfig — scaffold writing
// ---------------------------------------------------------------------------

/**
 * Write a scaffold demoforge.yaml to the target directory.
 *
 * Does NOT overwrite an existing config file.
 *
 * @param dir — directory to write the scaffold to
 */
export async function initConfig(dir: string): Promise<void> {
  const targetDir = path.resolve(dir);

  // Check if config already exists
  for (const name of CONFIG_FILENAMES) {
    if (fs.existsSync(path.join(targetDir, name))) {
      console.warn(
        `[demoforge] ${name} already exists in ${targetDir}. Skipping scaffold.`,
      );
      return;
    }
  }

  fs.writeFileSync(path.join(targetDir, "demoforge.yaml"), SCAFFOLD_TEMPLATE);
}
