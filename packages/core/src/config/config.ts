/**
 * DemoForge configuration system.
 *
 * Loads `demoforge.yaml` from CWD or parent directories, validates it,
 * and provides sensible defaults for all optional fields.
 *
 * Config injection pattern: config is loaded once at CLI entry and passed
 * down through the call chain as a function parameter. No global singletons.
 */

import * as fs from "node:fs";
import * as path from "node:path";
import yaml from "js-yaml";

import { ViewportConfig, NarrationMode } from "../types/index.js";
import { ConfigError } from "../errors/index.js";

// ---------------------------------------------------------------------------
// Config type
// ---------------------------------------------------------------------------

/** Redaction rule definition. */
export interface RedactionRule {
  pattern: string;
  label: string;
}

/** Output size budgets per format (bytes). */
export interface OutputBudgets {
  mp4?: number;
  webm?: number;
  gif?: number;
  webp?: number;
}

/** Output format configuration. */
export interface OutputConfig {
  formats: ("mp4" | "webm" | "gif" | "webp")[];
  budgets: OutputBudgets;
}

/** LLM endpoint configuration. */
export interface LLMConfig {
  base_url: string;
  model: string;
  context_budget: number;
}

/** Seed-data hook configuration. */
export interface SeedConfig {
  command?: string;
  timeout: number;
}

/** Render matrix configuration. */
export interface RenderConfig {
  viewports: ViewportConfig[];
  themes: ("light" | "dark")[];
  locales: string[];
}

/** Explorer agent configuration. */
export interface ExplorerConfig {
  maxSteps?: number;
  maxTime?: number;
  guardrails?: {
    allowedOrigins?: string[];
    destructiveButtonPatterns?: string[];
    destructiveUrlPatterns?: string[];
  };
}

/** Top-level DemoForge configuration. */
export interface Config {
  demo: string;
  title?: string;
  llm: LLMConfig;
  render: RenderConfig;
  seed: SeedConfig;
  redaction: RedactionRule[];
  output: OutputConfig;
  narration: { mode: NarrationMode; voice?: string; speed?: number };
  explorer: ExplorerConfig;
}

