/**
 * DemoForge core — heal module types.
 *
 * Types for LLM-assisted selector repair on replay failure.
 */

import type { DemoScript, DemoStep } from "../types/index.js";
import type { PageState, AccessibilityNode } from "../explorer/types.js";

// ─── Heal Context ─────────────────────────────────────────────────────────────

/** Information about a failing step that needs healing. */
export interface FailingStep {
  /** The step index in the script (0-based) */
  stepIndex: number;
  /** The failing step itself */
  step: DemoStep;
  /** The action type (click, fill, hover, etc.) */
  actionType: string;
  /** The old selector that failed */
  oldSelector: string;
  /** The error that caused the failure */
  error: string;
  /** The URL the script was on when it failed */
  url: string;
}

/** A selector patch proposed by the LLM. */
export interface SelectorPatch {
  /** The old selector that was failing */
  oldSelector: string;
  /** The new selector to use instead */
  newSelector: string;
  /** The action type this selector is for */
  actionType: string;
  /** Step index this patch applies to */
  stepIndex: number;
  /** Human-readable explanation of why this patch was chosen */
  explanation: string;
  /** Confidence score (0-1) of the proposed selector */
  confidence: number;
}

/** The LLM response for a healing request. */
export interface HealLlmResponse {
  /** The selector patches to apply */
  patches: SelectorPatch[];
  /** Overall explanation of the healing strategy */
  explanation: string;
}

// ─── Heal Result ──────────────────────────────────────────────────────────────

/** A proposal generated by the heal engine. */
export interface HealProposal {
  /** The failing step information */
  failingStep: FailingStep;
  /** The LLM-proposed selector patches */
  patches: SelectorPatch[];
  /** The accessibility tree snapshot at failure time */
  axTree: AccessibilityNode[];
  /** The page state at failure time */
  pageState: PageState;
  /** Base64-encoded screenshot of the page at failure time */
  screenshotBase64?: string;
  /** Whether the proposal was auto-accepted */
  accepted: boolean;
  /** The healed script with patches applied (if accepted) */
  healedScript?: DemoScript;
  /** The diff representation of changes */
  diff: string;
}

/** Result of the heal operation. */
export interface HealResult {
  /** Whether healing was successful */
  success: boolean;
  /** The healed demo script (if successful) */
  script?: DemoScript;
  /** List of proposals presented to the user */
  proposals: HealProposal[];
  /** Error message if healing failed */
  error?: string;
  /** Whether the LLM was unavailable */
  llmUnavailable: boolean;
  /** Number of patches applied */
  patchesApplied: number;
}

// ─── Heal Configuration ───────────────────────────────────────────────────────

/** Configuration for the heal engine. */
export interface HealConfig {
  /** The demo script to heal */
  script: DemoScript;
  /** The browser session for capturing page state */
  browser: import("@demoforge/browser").BrowserSession;
  /** The LLM client for proposing repairs */
  llmClient: import("../llm/client.js").LlmClient;
  /** Output directory for healed scripts */
  outputDir: string;
  /** Whether to auto-accept proposed repairs */
  accept: boolean;
  /** Screenshot output path */
  screenshotPath?: string;
  /** Maximum number of healing attempts per failing step */
  maxAttempts?: number;
  /** Minimum confidence threshold for auto-accept (0-1) */
  minConfidence?: number;
}

/** A reviewable diff entry for a single selector change. */
export interface SelectorDiff {
  /** Step index */
  stepIndex: number;
  /** Action type */
  actionType: string;
  /** The old (broken) selector */
  oldSelector: string;
  /** The new (proposed) selector */
  newSelector: string;
  /** Human-readable explanation */
  explanation: string;
}
