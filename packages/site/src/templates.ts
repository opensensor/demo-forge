/**
 * DemoForge site generator — HTML template generation.
 *
 * Generates vanilla HTML pages with embedded CSS/JS for:
 * - Index page: gallery of all flows with thumbnails
 * - Per-flow pages: video player, step timeline, captions, copyable narration
 */

import type { FlowInfo, SiteConfig } from "./site-generator.js";

// ─── Index Page Template ──────────────────────────────────────────────────────

export function generateIndexPage(flows: FlowInfo[], config: SiteConfig): string {
  const tags = config.showTags ? getUniqueTags(flows) : [];
  const searchHtml = config.searchEnabled ? generateSearchHtml() : "";

  const flowCards = flows
    .map(
      (flow) => `
    <div class="flow-card" data-name="${escapeAttr(flow.name)}" data-tags="${escapeAttr(flow.tags.join(","))}">
      <div class="flow-thumbnail">
        ${
          flow.thumbnail
            ? `<img src="assets/${flow.name}-thumb${extname(flow.thumbnail) || ".png"}" alt="${escapeAttr(flow.title)}" loading="lazy">`
            : `<div class="flow-thumbnail-placeholder"><svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><polygon points="5 3 19 12 5 21 5 3"></polygon></svg></div>`
        }
        <span class="flow-duration">${formatDuration(flow.duration)}</span>
      </div>
      <div class="flow-info">
        <h3 class="flow-title"><a href="flows/${flow.name}.html">${escapeHtml(flow.title)}</a></h3>
        ${
          flow.narration
            ? `<p class="flow-description">${escapeHtml(flow.narration)}</p>`
            : ""
        }
        ${
          config.showTags && flow.tags.length > 0
            ? `<div class="flow-tags">${flow.tags.map((t: string) => `<span class="tag">${escapeHtml(t)}</span>`).join("")}</div>`
            : ""
        }
        <a href="flows/${flow.name}.html" class="flow-link">View Demo &rarr;</a>
      </div>
    </div>`
    )
    .join("");

  const tagFilters = tags
    .map(
      (tag) =>
        `<button class="tag-filter" data-tag="${escapeAttr(tag)}" onclick="filterByTag('${escapeAttr(tag)}')">${escapeHtml(tag)}</button>`
    )
    .join("");

  return `<!DOCTYPE html>
<html lang="en" data-theme="${config.theme.mode}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(config.siteTitle)}</title>
  <link rel="stylesheet" href="css/site.css">
  <meta name="description" content="${escapeAttr(config.description || "")}">
</head>
<body>
  <header class="site-header">
    <div class="container">
      <h1 class="site-title">${escapeHtml(config.siteTitle)}</h1>
      <p class="site-description">${escapeHtml(config.description || "")}</p>
      <div class="header-controls">
        ${searchHtml}
        <button class="theme-toggle" id="themeToggle" aria-label="Toggle theme">
          <svg class="sun-icon" xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="5"></circle><line x1="12" y1="1" x2="12" y2="3"></line><line x1="12" y1="21" x2="12" y2="23"></line><line x1="4.22" y1="4.22" x2="5.64" y2="5.64"></line><line x1="18.36" y1="18.36" x2="19.78" y2="19.78"></line><line x1="1" y1="12" x2="3" y2="12"></line><line x1="21" y1="12" x2="23" y2="12"></line><line x1="4.22" y1="19.78" x2="5.64" y2="18.36"></line><line x1="18.36" y1="5.64" x2="19.78" y2="4.22"></line></svg>
          <svg class="moon-icon" xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z"></path></svg>
        </button>
      </div>
      ${config.showTags && tags.length > 0 ? `<div class="tag-filters">${tagFilters}</div>` : ""}
    </div>
  </header>
  <main class="container">
    <div class="flow-grid" id="flowGrid">
      ${flowCards}
    </div>
    ${flows.length === 0 ? '<p class="empty-state">No demos found. Run "demoforge render" to generate demo assets.</p>' : ""}
  </main>
  <footer class="site-footer">
    <div class="container">
      <p>Generated by <a href="https://github.com/demoforge" target="_blank">DemoForge</a></p>
    </div>
  </footer>
  <script src="js/site.js"></script>
</body>
</html>`;
}

// ─── Per-Flow Page Template ───────────────────────────────────────────────────

export function generateFlowPage(flow: FlowInfo, config: SiteConfig): string {
  const availableFormats = Object.keys(flow.videoFiles).filter(Boolean);
  const defaultFormat = config.defaultVideoFormat && flow.videoFiles[config.defaultVideoFormat] ? config.defaultVideoFormat : availableFormats[0] || "mp4";

  const videoPlayerHtml = availableFormats.length > 0
    ? `
  <div class="video-container">
    <div class="video-controls">
      ${availableFormats.map((fmt) => `<button class="format-btn ${fmt === defaultFormat ? "active" : ""}" data-format="${fmt}" onclick="switchFormat('${fmt}')">${fmt.toUpperCase()}</button>`).join("")}
    </div>
    ${availableFormats.map((fmt) => `
    <video class="video-player video-${fmt}" ${fmt !== defaultFormat ? 'style="display:none"' : ''} controls preload="metadata" poster="../assets/${flow.name}-thumb.png">
      <source src="../assets/${flow.name}.${fmt}" type="${getMimeType(fmt)}">
      Your browser does not support the video tag.
    </video>`).join("")}
  </div>`
    : `
  <div class="video-container">
    <div class="video-placeholder">
      <svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5"><polygon points="5 3 19 12 5 21 5 3"></polygon></svg>
      <p>No video available</p>
    </div>
  </div>`;

  const stepTimelineHtml = flow.steps && flow.steps.length > 0
    ? flow.steps
        .filter((s: any) => !s.done && !s.mark_flow_start && !s.mark_flow_end)
        .map((step: any, index: number) => {
          const stepType = getStepType(step);
          const stepDesc = getStepDescription(step);
          const stepIcon = getStepIcon(stepType);
          return `
    <div class="timeline-item" data-step="${index}">
      <div class="timeline-marker">
        <span class="timeline-number">${index + 1}</span>
        <span class="timeline-icon">${stepIcon}</span>
      </div>
      <div class="timeline-content">
        <div class="timeline-header">
          <span class="timeline-type">${escapeHtml(stepType)}</span>
          ${flow.screenshotFiles && flow.screenshotFiles[index] ? `<span class="timeline-screenshot"><img src="../assets/${flow.name}-${basename(flow.screenshotFiles[index])}" alt="Step ${index + 1}" loading="lazy"></span>` : ""}
        </div>
        <p class="timeline-description">${escapeHtml(stepDesc)}</p>
        ${step.narrate ? `<div class="timeline-narration"><p>${escapeHtml(step.narrate)}</p><button class="copy-btn" data-text="${escapeAttr(step.narrate)}" onclick="copyFromDataAttr(this)">Copy</button></div>` : ""}
      </div>
    </div>`;
        })
        .join("")
    : '<p class="empty-state">No steps recorded for this flow.</p>';

  const tagsHtml = config.showTags && flow.tags.length > 0
    ? `<div class="flow-tags">${flow.tags.map((t: string) => `<span class="tag">${escapeHtml(t)}</span>`).join("")}</div>`
    : "";

  const metadataHtml = config.showMetadata && flow.metadata
    ? `
  <div class="flow-metadata">
    <div class="metadata-item"><span class="metadata-label">Duration</span><span class="metadata-value">${formatDuration(flow.metadata.duration)}</span></div>
    <div class="metadata-item"><span class="metadata-label">Resolution</span><span class="metadata-value">${flow.metadata.width}x${flow.metadata.height}</span></div>
    <div class="metadata-item"><span class="metadata-label">FPS</span><span class="metadata-value">${flow.metadata.fps}</span></div>
    <div class="metadata-item"><span class="metadata-label">Codec</span><span class="metadata-value">${escapeHtml(flow.metadata.codec)}</span></div>
    <div class="metadata-item"><span class="metadata-label">Size</span><span class="metadata-value">${formatFileSize(flow.metadata.fileSize)}</span></div>
  </div>`
    : "";

  const effectsHtml = flow.effects && flow.effects.length > 0
    ? `
  <div class="effects-section">
    <h3>Effects Applied</h3>
    <ul class="effects-list">
      ${flow.effects.map((eff: any) => `<li><span class="effect-badge effect-${eff.type}">${escapeHtml(eff.type)}${eff.text ? `: ${escapeHtml(eff.text)}` : ""}</span></li>`).join("")}
    </ul>
  </div>`
    : "";

  return `<!DOCTYPE html>
<html lang="en" data-theme="${config.theme.mode}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(flow.title)} — ${escapeHtml(config.siteTitle)}</title>
  <link rel="stylesheet" href="../css/site.css">
  <meta name="description" content="${escapeAttr(flow.narration || flow.title)}">
</head>
<body>
  <header class="site-header">
    <div class="container">
      <nav class="breadcrumb"><a href="../index.html">&larr; All Demos</a></nav>
      <h1 class="flow-page-title">${escapeHtml(flow.title)}</h1>
      ${tagsHtml}
    </div>
  </header>
  <main class="container">
    <div class="flow-layout">
      <div class="flow-main">
        ${videoPlayerHtml}
        ${metadataHtml}
        ${effectsHtml}
      </div>
      <div class="flow-sidebar">
        <div class="flow-summary">
          ${flow.narration ? `<h3>Overview</h3><p>${escapeHtml(flow.narration)}</p>` : ""}
          <div class="flow-stats">
            <span class="stat">${flow.stepCount} steps</span>
            ${flow.duration ? `<span class="stat">${formatDuration(flow.duration)}</span>` : ""}
          </div>
        </div>
      </div>
    </div>
    <section class="step-timeline">
      <h2>Step Timeline</h2>
      <div class="timeline">
        ${stepTimelineHtml}
      </div>
    </section>
  </main>
  <footer class="site-footer">
    <div class="container">
      <p><a href="../index.html">&larr; Back to all demos</a> | Generated by <a href="https://github.com/demoforge" target="_blank">DemoForge</a></p>
    </div>
  </footer>
  <script src="../js/site.js"></script>
</body>
</html>`;
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function getUniqueTags(flows: FlowInfo[]): string[] {
  const tagSet = new Set<string>();
  for (const flow of flows) {
    for (const tag of flow.tags) {
      tagSet.add(tag);
    }
  }
  return Array.from(tagSet).sort();
}

function getStepType(step: any): string {
  if (step.goto) return "Navigate";
  if (step.click) return "Click";
  if (step.hover) return "Hover";
  if (step.fill) return "Fill";
  if (step.select) return "Select";
  if (step.press) return "Press";
  if (step.scroll) return "Scroll";
  if (step.wait_for) return "Wait";
  if (step.narrate) return "Narrate";
  if (step.screenshot) return "Screenshot";
  if (step.pause) return "Pause";
  return "Action";
}

function getStepDescription(step: any): string {
  if (step.goto) return `Navigate to ${step.goto}`;
  if (step.click) return `Click ${typeof step.click === "string" ? step.click : JSON.stringify(step.click)}`;
  if (step.hover) return `Hover over ${typeof step.hover === "string" ? step.hover : JSON.stringify(step.hover)}`;
  if (step.fill) return `Fill ${typeof step.fill.target === "string" ? step.fill.target : JSON.stringify(step.fill.target)} with "${step.fill.value}"`;
  if (step.select) return `Select "${step.select.value}" from ${typeof step.select.target === "string" ? step.select.target : JSON.stringify(step.select.target)}`;
  if (step.press) return `Press ${step.press.key}`;
  if (step.scroll) return `Scroll by ${step.scroll.amount}px`;
  if (step.wait_for) {
    if (step.wait_for.text) return `Wait for text: "${step.wait_for.text}"`;
    if (step.wait_for.selector) return `Wait for selector: ${JSON.stringify(step.wait_for.selector)}`;
  }
  if (step.narrate) return step.narrate;
  return "Action";
}

function getStepIcon(stepType: string): string {
  const icons: Record<string, string> = {
    Navigate: "🌐",
    Click: "👆",
    Hover: "🔍",
    Fill: "✏️",
    Select: "📋",
    Press: "⌨️",
    Scroll: "↕️",
    Wait: "⏳",
    Narrate: "🎙️",
    Screenshot: "📸",
    Pause: "⏸️",
  };
  return icons[stepType] || "➡️";
}

function getMimeType(format: string): string {
  const mimeMap: Record<string, string> = {
    mp4: "video/mp4",
    webm: "video/webm",
    gif: "image/gif",
    webp: "image/webp",
  };
  return mimeMap[format] || "video/mp4";
}

/** Formats a duration given in milliseconds, e.g. 10000 → "10s", 100000 → "1m 40s". */
function formatDuration(ms?: number): string {
  if (!ms) return "";
  const totalSeconds = Math.round(ms / 1000);
  const m = Math.floor(totalSeconds / 60);
  const s = totalSeconds % 60;
  return m > 0 ? `${m}m ${s}s` : `${s}s`;
}

function formatFileSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function escapeAttr(str: string): string {
  return escapeHtml(str);
}



function extname(path: string): string {
  return path.includes(".") ? path.slice(path.lastIndexOf(".")) : ".png";
}

function basename(path: string): string {
  return path.split("/").pop() || path;
}

function generateSearchHtml(): string {
  return `
        <div class="search-container">
          <input type="search" id="searchInput" placeholder="Search demos..." class="search-input">
          <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" class="search-icon"><circle cx="11" cy="11" r="8"></circle><line x1="21" y1="21" x2="16.65" y2="16.65"></line></svg>
        </div>`;
}
